// Writes public/bd-example-us-briefs.js: the matter brief each United States worked example loads at B0 (development
// plan task US.5), built with the AI Obligations Atlas's own code from its published snapshot, then read as the app
// reads an uploaded brief. Run when the Atlas's US records change:
//   node tools/build-us-example-briefs.mjs ../obligations-atlas
// The snapshot is the Atlas's published one (data/snapshot/ai-obligations-atlas.json). --preview uses the preview
// snapshot instead, marked as such in every brief, for a trial before the records are approved.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readBrief } from '../public/shared/matter-brief.js';
const atlasDir = process.argv[2], preview = process.argv.includes('--preview');
if (!atlasDir) { console.error('Usage: node tools/build-us-example-briefs.mjs <path to obligations-atlas> [--preview]'); process.exit(1); }
const { Atlas, buildMatterBrief } = await import(pathToFileURL(join(atlasDir, 'src/core/atlas.js')).href);
const snapshot = JSON.parse(readFileSync(join(atlasDir, 'data/snapshot', preview ? 'ai-obligations-atlas.preview.json' : 'ai-obligations-atlas.json'), 'utf8'));
const data = new Atlas(snapshot, { preview }).dataset();
const C = JSON.parse(readFileSync(new URL('../public/bd-content.json', import.meta.url), 'utf8'));
const names = { entityTypes: Object.fromEntries(C.entityTypes), jurisdictions: Object.fromEntries(C.jurisdictions) };
// Each example's scope: its jurisdictions, entity type, sector and the use cases its inventory has. Harlow Ridge Bank is
// chartered in New York, so its brief takes the federal records and New York's (US-NY); the others operate in several
// states and take every state's, each named by its state.
const SCOPES = {
  bank: { jurisdictions: ['US', 'US-NY'], entityTypes: ['bank'], sectors: ['US-BANKING'], useCaseIDs: ['UC2', 'UC3', 'UC7'], loadedOn: '2026-10-23' },
  insurer: { entityTypes: ['insurer'], sectors: ['US-INSURANCE'], useCaseIDs: ['UC3', 'UC4', 'UC7'], loadedOn: '2026-10-30' },
  securities: { entityTypes: ['capitalMarketsIntermediary'], sectors: ['US-SECURITIES'], useCaseIDs: ['UC2', 'UC5', 'UC7'], loadedOn: '2026-11-02' },
  health: { entityTypes: ['healthServiceProvider'], sectors: ['US-HEALTH'], useCaseIDs: ['UC1', 'UC2', 'UC7'], loadedOn: '2026-11-06' },
  grid: { entityTypes: ['criticalInfrastructureAssetOwner'], sectors: ['US-CRITICAL-INFRASTRUCTURE'], useCaseIDs: ['UC5', 'UC6', 'UC7'], loadedOn: '2026-11-09' },
};
const out = {};
for (const [k, s] of Object.entries(SCOPES)) {
  const b = buildMatterBrief(data, { matterLabel: 'Worked example', jurisdictions: s.jurisdictions || ['US'], entityTypes: s.entityTypes, sectors: s.sectors, useCaseIDs: s.useCaseIDs });
  const r = readBrief(JSON.stringify(b), names, s.loadedOn, 'Lee Chan');
  if (r.error) throw new Error(`${k}: ${r.error}`);
  const n = r.brief.tiers.reduce((t, x) => t + x.refs.length, 0), us = r.brief.tiers.flatMap(x => x.refs).filter(x => /^OBL-US-/.test(x[0])).length;
  if (!us && !preview) throw new Error(`${k}: the published snapshot holds no US record for this scope yet; approve the US round in the Fabric and refresh the snapshots`);
  out[k] = r.brief;
  console.log(`${k}: ${n} references, ${us} of them US`);
}
writeFileSync(new URL('../public/bd-example-us-briefs.js', import.meta.url), `/* Generated by tools/build-us-example-briefs.mjs from the AI Obligations Atlas ${preview ? 'PREVIEW' : 'published'} snapshot (${data.info.generatedAt}). Do not edit. */\nwindow.BDUSBriefs = ${JSON.stringify(out)};\n`);
